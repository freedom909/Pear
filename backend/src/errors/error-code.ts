/**
 * 应用程序错误代码枚举
 *
 * 错误代码格式：
 * - 前缀: E表示错误
 * - 分类: 3位数字表示错误分类
 * - 序号: 3位数字表示具体错误
 *
 * 分类说明：
 * - 000: 通用错误
 * - 100: 认证/授权错误
 * - 200: 输入验证错误
 * - 300: 业务逻辑错误
 * - 400: 数据库错误
 * - 500: 外部服务错误
 * - 600: 系统错误
 */
