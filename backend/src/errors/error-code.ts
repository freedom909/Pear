  REGISTRATION_FAILED = 'E100010',

  // 输入验证错误 (200)
  
  VALIDATION_ERROR = 'E200001',
  INVALID_FORMAT = 'E200002',
  REQUIRED_FIELD_MISSING = 'E200003',
